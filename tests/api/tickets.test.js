import { test, mock, after } from 'node:test';
import assert from 'node:assert/strict';
process.env.JWT_SECRET = 'test-only-secret-with-more-than-32-characters';
Object.assign(process.env, { MAIL_HOST: 'smtp.example.com', MAIL_FROM: 'events@example.com', MAIL_PORT: '587' });
const { default: request } = await import('../helpers/request.js');
const { app } = await import('../../src/app.js');
const { unitOfWorkRepository } = await import('../../src/repositories/unit-of-work.repository.js');
const { default: nodemailer } = await import('nodemailer');
const { generateToken } = await import('../../src/utils/jwt.js');
const { usersRepository } = await import('../../src/repositories/users.repository.js');
const { eventsRepository } = await import('../../src/repositories/events.repository.js');
const { ticketsRepository } = await import('../../src/repositories/tickets.repository.js');
const owner = { _id: '1'.repeat(24), email: 'owner@example.com', role: 'user' };
const other = { _id: '2'.repeat(24), email: 'other@example.com', role: 'user' };
const organizer = { _id: '3'.repeat(24), email: 'organizer@example.com', role: 'organizer' };
const stranger = { _id: '4'.repeat(24), email: 'stranger@example.com', role: 'organizer' };
const users = [owner, other, organizer, stranger];
const id = 'a'.repeat(24);
const event = { _id: id, title: 'Taller', date: new Date('2099-05-01'), status: 'published', capacity: 2, organizer: organizer._id };
const tickets = [];
const cookie = (user) => `currentUser=${generateToken(user)}`;
mock.method(usersRepository, 'findById', async (id) => users.find((u) => u._id === id));
mock.method(unitOfWorkRepository, 'run', async (work) => work({}));
mock.method(eventsRepository, 'lockForReservation', async (value) => value === id ? event : null);
mock.method(eventsRepository, 'findById', async (value) => value === id ? event : null);
mock.method(ticketsRepository, 'findActiveRegistration', async (event, user) => tickets.find((t) => t.user === user && t.status !== 'cancelled'));
mock.method(ticketsRepository, 'countReservedPlaces', async () => tickets.filter((t) => t.status !== 'cancelled').reduce((sum, t) => sum + t.quantity, 0));
mock.method(ticketsRepository, 'createTicket', async (data) => { const ticket = { ...data, _id: (tickets.length + 10).toString(16).padStart(24, '0'), cancelledAt: null }; tickets.push(ticket); return ticket; });
mock.method(ticketsRepository, 'findById', async (id) => tickets.find((t) => t._id === id) ?? null);
mock.method(ticketsRepository, 'cancelTicket', async (id, cancelledAt) => Object.assign(tickets.find((ticket) => ticket._id === id), { status: 'cancelled', cancelledAt }));
mock.method(ticketsRepository, 'findUserTickets', async (user) => tickets.filter((t) => t.user === user));
mock.method(ticketsRepository, 'findEventTickets', async () => tickets);
const sendMail = mock.fn(async () => ({ accepted: ['owner@example.com'] }));
mock.method(nodemailer, 'createTransport', () => ({ sendMail }));
after(() => mock.restoreAll());
test('Inscripción, correo simulado, duplicados, cupos, cancelación e historial', async () => {
  const reserve = (user, quantity = 1, eventId = id) => request(app).post(`/api/events/${eventId}/tickets`).set('Cookie', cookie(user)).send({ quantity });
  const first = await reserve(owner, 2).expect(201);
  assert.equal(first.body.notification, 'sent'); assert.equal(sendMail.mock.callCount(), 1);
  assert.equal(sendMail.mock.calls[0].arguments[0].to, owner.email);
  assert.match(sendMail.mock.calls[0].arguments[0].text, /Código:/);
  await reserve(owner).expect(409); await reserve(other).expect(409);
  await reserve(other, 1, 'b'.repeat(24)).expect(404);
  for (const status of ['cancelled', 'finished', 'draft']) { event.status = status; await reserve(other).expect(409); }
  event.status = 'published'; event.date = new Date('2000-01-01'); await reserve(other).expect(409); event.date = new Date('2099-05-01');
  const tid = first.body.payload._id;
  await request(app).patch(`/api/tickets/${tid}/cancel`).set('Cookie', cookie(other)).expect(403);
  const cancelled = await request(app).patch(`/api/tickets/${tid}/cancel`).set('Cookie', cookie(owner)).expect(200);
  assert.equal(cancelled.body.payload.status, 'cancelled'); assert.ok(cancelled.body.payload.cancelledAt);
  await request(app).patch(`/api/tickets/${tid}/cancel`).set('Cookie', cookie(owner)).expect(409);
  await reserve(other, 2).expect(201);
  const mine = await request(app).get('/api/tickets/my-tickets').set('Cookie', cookie(owner)).expect(200);
  assert.equal(mine.body.payload.length, 1); assert.equal(mine.body.payload[0].status, 'cancelled');
  await request(app).get(`/api/events/${id}/tickets`).set('Cookie', cookie(owner)).expect(403);
  await request(app).get(`/api/events/${id}/tickets`).set('Cookie', cookie(stranger)).expect(403);
  await request(app).get(`/api/events/${id}/tickets`).set('Cookie', cookie(organizer)).expect(200);
  // La inscripción sigue vigente si falla el proveedor de correo.
  const active = tickets.find((t) => t.status === 'confirmed');
  await request(app).patch(`/api/tickets/${active._id}/cancel`).set('Cookie', cookie(other)).expect(200);
  mock.method(nodemailer, 'createTransport', () => ({ sendMail: async () => { throw new Error('SMTP no disponible'); } }));
  const failed = await reserve(owner).expect(201); assert.equal(failed.body.notification, 'failed'); assert.equal(failed.body.payload.status, 'confirmed');
});
